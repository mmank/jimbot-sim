def eligible_bosses(ante: int, used: dict, win_ante: int = 8) -> list:
    """Boss keys the game would consider for this ante, least-used only.

    Two filters, and the second is the one that is easy to miss. Showdown
    bosses appear only on the ante that ends a run; ordinary ones only when it
    does not. Then the set is narrowed to those used fewest so far, which is
    why a run does not see the same boss twice while others are unplayed --
    a uniform draw over all eligible bosses is a different game.
    """
    ante = max(1, ante)
    finisher = ante % win_ante == 0 and ante >= 2
    pool = []
    for key, (_name, min_ante, showdown, _mult) in BOSS_DATA.items():
        if showdown:
            if finisher:
                pool.append(key)
        elif min_ante <= ante and not finisher:
            pool.append(key)

    if not pool:
        return []
    fewest = min(used.get(key, 0) for key in pool)
    # Keys sorted, because pseudorandom_element sorts a keyed table before it
    # picks and the order therefore decides which key an index lands on.
    return sorted(key for key in pool if used.get(key, 0) == fewest)
