"""Boss blinds and how the game picks one.

Generated by ops/gen_boss_data.py. Do not edit by hand.

`min` is the earliest ante a boss can appear at. `showdown` marks the finisher
bosses, which appear only on the ante that ends a run and never before ante 2.
`mult` is the blind's chip multiplier.

The order here is alphabetical by key on purpose: the game draws with
pseudorandom_element over a keyed table, which sorts the keys before picking,
so alphabetical order is part of the distribution.
"""

