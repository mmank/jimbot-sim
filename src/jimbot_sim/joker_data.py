def pool_for_rarity(rarity: int) -> list:
    """Joker keys of that rarity, in the game's pool order."""
    return [key for _, (key, r, _order, _u, _g, _n, _y)
            in sorted(JOKER_DATA.items(), key=lambda kv: kv[1][2])
            if r == rarity]
